await page.locator('#quote-dialog input').fill('3');
await page.locator('#quote-dialog input').dispatchEvent('change');
assert.equal(await page.locator('[data-quote-count]').textContent(), '3');
const downloadEvent = page.waitForEvent('download');
await page.locator('#quote-download').click();
const download = await downloadEvent;
assert.equal(download.suggestedFilename(), 'ayala-lista-demo.txt');
