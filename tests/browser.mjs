import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || '/opt/google/chrome/chrome', headless: true });
mkdirSync('tests/artifacts', { recursive: true });
const page = await browser.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
const response = await page.goto('http://127.0.0.1:8080/');
assert.equal(response.status(), 200);
await page.waitForSelector('.swiper-initialized');
await page.evaluate(async () => { await document.fonts.ready; await Promise.all([...document.images].map(async image => { image.loading = 'eager'; try { await image.decode(); } catch {} })); });
for (const width of [360, 390, 768, 1024, 1440]) {
  await page.setViewportSize({ width, height: 1000 });
  await page.screenshot({ path: `tests/artifacts/home-${width}.png`, fullPage: true });
  await page.screenshot({ path: `tests/artifacts/top-${width}.png` });
  assert.equal(await page.locator('.hero-pagination button').evaluateAll(buttons => buttons.every(button => button.getBoundingClientRect().width >= 44 && button.getBoundingClientRect().height >= 44)), true, `Slider touch controls at ${width}`);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `Overflow at ${width}`);
  assert.equal(await page.locator('img').evaluateAll(images => images.every(image => image.complete && image.naturalWidth > 0)), true, `Images at ${width}`);
}
await page.locator('#hero-next').click();
await page.waitForTimeout(600);
assert.match(await page.locator('#slide-number').textContent(), /02/);
