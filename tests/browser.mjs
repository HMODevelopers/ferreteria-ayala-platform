await page.locator('#menu-open').click();
assert.equal(await page.locator('#menu-open').getAttribute('aria-expanded'), 'true');
for (const key of ['Tab', 'Shift+Tab']) for (let i = 0; i < 12; i++) { await page.keyboard.press(key); assert.equal(await page.locator('#mobile-menu').evaluate(node => node.contains(document.activeElement)), true); }
await page.keyboard.press('Escape');
